#!/usr/bin/env python3
"""Generates ath9k/.../Initvals.kt from Linux's drivers/net/wireless/ath/ath9k/ar9002_initvals.h (ISC licence).

Only the AR9271's tables are taken. Usage:
    curl -sLO https://raw.githubusercontent.com/torvalds/linux/master/drivers/net/wireless/ath/ath9k/ar9002_initvals.h
    python3 tools/ath9k/make_initvals.py ar9002_initvals.h
"""
import os
import re
import sys

TABLES = ["ar9271Modes_9271", "ar9271Common_9271", "ar9271Modes_9271_ANI_reg",
          "ar9271Modes_normal_power_tx_gain_9271", "ar9271Modes_high_power_tx_gain_9271"]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../ath9k/src/main/kotlin/io/github/banaanga/sniffowireless/mobile/ath9k/Initvals.kt")


def table(src, name):
    m = re.search(r"static const u32 %s\[\]\[(\d+)\] = \{(.*?)\n\};" % re.escape(name), src, re.S)
    if not m:
        sys.exit("table %s not found" % name)
    cols = int(m.group(1))
    rows = []
    for row in re.findall(r"\{([^{}]*)\}", m.group(2)):
        vals = [v.strip() for v in row.split(",") if v.strip()]
        if len(vals) != cols:
            sys.exit("%s: row with %d values, expected %d" % (name, len(vals), cols))
        rows.append([int(v, 0) for v in vals])
    return cols, rows


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    out = ["package io.github.banaanga.sniffowireless.mobile.ath9k", "",
           "// Generated by tools/ath9k/make_initvals.py from Linux's ar9002_initvals.h (ISC licence, see NOTICE). Don't edit.",
           "", "/** The AR9271's initial register values, as rows of [register, value per column…]. */",
           "internal object Initvals {"]
    for name in TABLES:
        cols, rows = table(src, name)
        parts = [x for x in name.replace("ar9271", "").replace("_9271", "").split("_") if x]
        kname = parts[0][0].lower() + parts[0][1:] + "".join(x[0].upper() + x[1:] for x in parts[1:])
        out.append("    /** %s: %d rows of %d columns. */" % (name, len(rows), cols))
        out.append("    val %s = Ini(%d, intArrayOf(" % (kname, cols))
        for r in rows:
            out.append("        " + ", ".join("0x%08x.toInt()" % v if v > 0x7fffffff else "0x%08x" % v for v in r) + ",")
        out.append("    ))")
    out.append("}")
    out.append("")
    out.append("/** An initvals table: [rows] × [columns] values, column 0 being the register. */")
    out.append("internal class Ini(val columns: Int, val data: IntArray) {")
    out.append("    val rows get() = data.size / columns")
    out.append("    fun reg(row: Int) = data[row * columns]")
    out.append("    fun value(row: Int, column: Int) = data[row * columns + column]")
    out.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
