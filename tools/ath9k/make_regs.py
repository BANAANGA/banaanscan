#!/usr/bin/env python3
"""Generates ath9k/.../Regs_gen.kt: the values of the register and bit-field names Ar9271.kt uses, taken from Linux's
headers (ISC licence) by compiling a small C program against them, so they are exactly what Linux uses for an AR9271.

Needs gcc and these headers from drivers/net/wireless/ath/ath9k/ (reg.h, phy.h, ar9002_phy.h) plus ../reg.h, in DIR:
    python3 tools/ath9k/make_regs.py DIR
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "../../ath9k/src/main/kotlin/io/github/banaanga/sniffowireless/mobile/ath9k")
OUT = os.path.join(SRC, "Regs_gen.kt")
HEADERS = ["reg.h", "phy.h", "ar9002_phy.h"]


def main():
    d = os.path.abspath(sys.argv[1])
    code = open(os.path.join(SRC, "Ar9271.kt"), encoding="utf-8").read()
    fields = sorted(set(re.findall(r"\b([A-Z][A-Za-z0-9_]*)\.v\b", code)) | set(re.findall(r"sm\([^,]+,\s*([A-Z][A-Za-z0-9_]*)\)", code)))
    shifts = sorted(set(n for n in re.findall(r"\b(AR[A-Za-z0-9_]*_S)\b", code)))
    headers = "".join(open(os.path.join(d, h), encoding="utf-8").read() for h in HEADERS)
    funclike = set(re.findall(r"#define\s+([A-Za-z0-9_]+)\(", headers))
    stub = r"""
#include <stdio.h>
typedef unsigned int u32; typedef unsigned short u16; typedef unsigned char u8; typedef signed char s8;
#define BIT(n) (1U << (n))
struct hwv { unsigned macVersion, macRev, phyRev, devid; };
struct ath_hw { struct hwv hw_version; int is_pciexpress; };
static struct ath_hw A = {{0x140, 1, 0, 0x9271}, 0};
static struct ath_hw *ah = &A;
""" + "".join('#include "%s"\n' % h for h in HEADERS) + "int main(void) {\n"
    for n in fields + shifts:
        expr = n + "(ah)" if n in funclike else n
        stub += '    printf("%s %%u\\n", (u32)(%s));\n' % (n, expr)
    stub += "    return 0;\n}\n"
    with tempfile.TemporaryDirectory() as tmp:
        c = os.path.join(tmp, "regs.c")
        open(c, "w").write(stub)
        exe = os.path.join(tmp, "regs")
        r = subprocess.run(["gcc", "-w", "-I", d, "-o", exe, c], capture_output=True, text=True)
        if r.returncode:
            sys.exit(r.stderr)
        values = dict(line.split() for line in subprocess.run([exe], capture_output=True, text=True, check=True).stdout.splitlines())
    out = ["package io.github.banaanga.sniffowireless.mobile.ath9k", "",
           "// Generated by tools/ath9k/make_regs.py from Linux's ath9k register headers (ISC licence, see NOTICE). Don't edit.",
           "", "/** Registers and bit fields, with their values for the AR9271. */",
           "@Suppress(\"EnumEntryName\")", "internal enum class R(val v: Int) {"]
    for n in fields:
        out.append("    %s(0x%08x.toInt())," % (n, int(values[n])))
    out.append("}")
    out.append("")
    for n in shifts:
        out.append("internal const val %s = %s" % (n, values[n]))
    out.append("")
    out.append("/** AR_PHY(n): baseband register n. */")
    out.append("internal fun AR_PHY(n: Int) = 0x9800 + (n shl 2)")
    out.append("/** AR_PHY_TIMING_CTRL4(chain) */")
    out.append("internal fun AR_PHY_TIMING_CTRL4(chain: Int) = 0x9920 + chain * 0x1000")
    out.append("/** AR_QSTS(queue) */")
    out.append("internal fun AR_QSTS(q: Int) = 0x0a00 + (q shl 2)")
    out.append("/** AR_DQCUMASK(dcu) */")
    out.append("internal fun AR_DQCUMASK(dcu: Int) = 0x1000 + (dcu shl 2)")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %d names, %d shifts to %s" % (len(fields), len(shifts), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
